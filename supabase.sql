-- HOMEWORK DIARY database
-- Run this whole file in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('Teacher','Student')),
  full_name text not null,
  father_name text,
  email text not null,
  age integer check (age between 5 and 100),
  gender text,
  institution_type text not null,
  institution_name text not null,
  class_name text not null,
  section text not null,
  group_name text,
  roll_number text,
  photo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.homework (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  subject text not null,
  title text,
  homework_text text not null,
  due_date date,
  recipient_user_id uuid references public.profiles(id) on delete cascade,
  recipient_institution_name text not null,
  recipient_class_name text not null,
  recipient_section text not null,
  recipient_group_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.homework_completions (
  homework_id bigint not null references public.homework(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key (homework_id, student_id)
);

create index if not exists profiles_email_idx on public.profiles(lower(email));
create index if not exists homework_teacher_idx on public.homework(teacher_id);
create index if not exists homework_recipient_idx on public.homework(recipient_user_id);

alter table public.profiles enable row level security;
alter table public.homework enable row level security;
alter table public.homework_completions enable row level security;

-- Create a profile automatically when Supabase Auth creates an account.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (
    id, role, full_name, father_name, email, age, gender,
    institution_type, institution_name, class_name, section,
    group_name, roll_number
  )
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'role', 'Student'),
    coalesce(new.raw_user_meta_data->>'full_name', ''),
    new.raw_user_meta_data->>'father_name',
    new.email,
    nullif(new.raw_user_meta_data->>'age','')::integer,
    new.raw_user_meta_data->>'gender',
    coalesce(new.raw_user_meta_data->>'institution_type', 'Primary School'),
    coalesce(new.raw_user_meta_data->>'institution_name', ''),
    coalesce(new.raw_user_meta_data->>'class_name', ''),
    coalesce(new.raw_user_meta_data->>'section', ''),
    new.raw_user_meta_data->>'group_name',
    new.raw_user_meta_data->>'roll_number'
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Helper functions run with database-owner privileges so RLS policies do not
-- recursively query public.profiles.
create or replace function public.current_profile()
returns public.profiles
language sql
security definer
set search_path = public
stable
as $$
  select p from public.profiles p where p.id = auth.uid();
$$;

create or replace function public.is_teacher_for_class(
  target_institution text,
  target_class text,
  target_section text,
  target_group text
)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.role = 'Teacher'
      and p.institution_name = target_institution
      and p.class_name = target_class
      and p.section = target_section
      and coalesce(p.group_name,'') = coalesce(target_group,'')
  );
$$;

create or replace function public.current_student_matches(
  target_institution text,
  target_class text,
  target_section text,
  target_group text
)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid()
      and p.role = 'Student'
      and p.institution_name = target_institution
      and p.class_name = target_class
      and p.section = target_section
      and coalesce(p.group_name,'') = coalesce(target_group,'')
  );
$$;

-- Profiles: users see themselves. Teachers may see students in their matching class.
drop policy if exists "profile_select" on public.profiles;
create policy "profile_select" on public.profiles
for select to authenticated
using (
  id = auth.uid()
  or (
    role = 'Student'
    and public.is_teacher_for_class(institution_name, class_name, section, group_name)
  )
);

drop policy if exists "profile_update_own" on public.profiles;
create policy "profile_update_own" on public.profiles
for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

-- Homework: teacher can see their sent homework; students can see their direct
-- homework or homework sent to their matching institution/class/section/group.
drop policy if exists "homework_select" on public.homework;
create policy "homework_select" on public.homework
for select to authenticated
using (
  teacher_id = auth.uid()
  or (
    recipient_user_id = auth.uid()
    or (
      recipient_user_id is null
      and public.current_student_matches(
        recipient_institution_name,
        recipient_class_name,
        recipient_section,
        recipient_group_name
      )
    )
  )
);

drop policy if exists "homework_insert_teacher" on public.homework;
create policy "homework_insert_teacher" on public.homework
for insert to authenticated
with check (
  teacher_id = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role = 'Teacher'
  )
  and public.current_profile().institution_name = recipient_institution_name
  and public.current_profile().class_name = recipient_class_name
  and public.current_profile().section = recipient_section
  and coalesce(public.current_profile().group_name,'') = coalesce(recipient_group_name,'')
);

-- A student can mark only their own visible homework as finished.
drop policy if exists "completion_select" on public.homework_completions;
create policy "completion_select" on public.homework_completions
for select to authenticated
using (
  student_id = auth.uid()
  or exists (
    select 1 from public.homework h
    where h.id = homework_completions.homework_id
      and h.teacher_id = auth.uid()
  )
);

drop policy if exists "completion_insert" on public.homework_completions;
create policy "completion_insert" on public.homework_completions
for insert to authenticated
with check (
  student_id = auth.uid()
  and public.current_profile().role = 'Student'
  and exists (
    select 1 from public.homework h
    where h.id = homework_id
      and (
        h.recipient_user_id = auth.uid()
        or (
          h.recipient_user_id is null
          and public.current_student_matches(
            h.recipient_institution_name,
            h.recipient_class_name,
            h.recipient_section,
            h.recipient_group_name
          )
        )
      )
  )
);

-- Public profile photo bucket. The URL is only stored after the user uploads.
insert into storage.buckets (id, name, public)
values ('profile-photos', 'profile-photos', true)
on conflict (id) do update set public = true;

drop policy if exists "profile_photo_insert_own" on storage.objects;
create policy "profile_photo_insert_own" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'profile-photos'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);

drop policy if exists "profile_photo_update_own" on storage.objects;
create policy "profile_photo_update_own" on storage.objects
for update to authenticated
using (
  bucket_id = 'profile-photos'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
)
with check (
  bucket_id = 'profile-photos'
  and (storage.foldername(name))[1] = (select auth.uid()::text)
);
